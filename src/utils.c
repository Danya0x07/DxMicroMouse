int32_t NormalizeAngleDegrees(int32_t degAng)
{
    degAng %= 360;
    if (degAng > 180)
        degAng -= 360;
    else if (degAng <= -180)
        degAng += 360;
    return degAng;
}

int32_t Sin100000(int32_t degAng)
{
    int32_t sign = 1;

    if (degAng < 0) {
        sign = -1;
        degAng = -degAng;
    }

    if (degAng > 90)
        degAng = 180 - degAng;

    return sign * SIN_TABLE[degAng];
}

int32_t Cos100000(int32_t degAng)
{
    if (degAng < 0)
        degAng = -degAng;
    degAng = 90 - degAng;

    return Sin100000(degAng);
}